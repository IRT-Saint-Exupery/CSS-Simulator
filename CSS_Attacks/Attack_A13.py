import socket
import numpy as np
import time
from datetime import datetime

def send_to_socket(IP, PORT, command):

	byte_message = bytes(command)

	opened_socket = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)

	opened_socket.sendto(byte_message, (IP, PORT))	
	
	return


